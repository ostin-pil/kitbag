"""Single-source generator: turn the kitbag manifest (bundles.yaml) into a
distributable Claude Code *marketplace* repo.

Claude Code plugins have no plugin->plugin dependency field, so a bundle cannot
auto-pull its members declaratively. Instead each generated bundle becomes a tiny
plugin shipping a slash command that runs `kitbag bundle install <name>` — the
manifest stays the single source of truth and the marketplace is fully derived.

`build_marketplace()` is pure: it returns {relative_path: file_contents} so it can
be unit-tested without touching the filesystem. `write_tree()` flushes to disk.
"""
from __future__ import annotations
import json
from pathlib import Path

from .cli import resolve_bundle

SCHEMA_URL = "https://anthropic.com/claude-code/marketplace.schema.json"


def _author_obj(author):
    return author if isinstance(author, dict) else {"name": author}


def _plugin_json(name, description, author):
    return json.dumps({
        "name": name,
        "description": description,
        "version": "0.1.0",
        "author": _author_obj(author),
    }, indent=2) + "\n"


def _install_command(bundle, description, members):
    """Markdown slash-command that drives the kitbag CLI for one bundle."""
    plist = ", ".join(members["plugins"]) or "—"
    mlist = ", ".join(members["mcp"])
    mcp_line = f"\n- MCP servers: {mlist}" if mlist else ""
    return f"""---
description: Install the kitbag "{bundle}" bundle — {description}
---

# Install bundle: {bundle}

{description}

Run this in the terminal and report the outcome to the user:

```bash
kitbag bundle install {bundle}
```

This bundle contains:
- plugins: {plist}{mcp_line}

`kitbag` installs only what is missing (idempotent). Afterwards, remind the user
they may need to run `/reload-plugins` (or restart) for new components to load.
If `kitbag` is not installed, point them to it first.
"""


def _marketplace_json(name, description, author, entries):
    return json.dumps({
        "$schema": SCHEMA_URL,
        "name": name,
        "description": description,
        "owner": _author_obj(author),
        "plugins": entries,
    }, indent=2) + "\n"


def _readme(name, bundles, layout):
    rows = "\n".join(f"- **{b}** — {bundles[b].get('description','')}" for b in bundles)
    return f"""# {name}

A Claude Code marketplace generated by [kitbag](https://github.com/your-org/kitbag)
from a single `bundles.yaml`. Each entry is a curated bundle of plugins (and MCP
servers) for a workflow or specialization.

## Use it

```bash
claude plugin marketplace add <owner>/<this-repo>
claude plugin install <bundle>@{name}      # e.g. web, python, security
```

Installing a bundle plugin adds a slash command that runs `kitbag bundle install
<bundle>`, which installs the bundle's members (idempotently).

## Bundles

{rows}

---
*Generated — do not edit by hand. Edit `bundles.yaml` in the kitbag repo and
re-run `kitbag generate marketplace`. Layout: `{layout}`.*
"""


def build_marketplace(manifest, *, name="kitbag-bundles",
                      description="Curated Claude Code plugin bundles (generated by kitbag)",
                      author="kitbag authors", layout="per-bundle"):
    """Return {relpath: contents} for a complete marketplace repo. Pure."""
    bundles = manifest.get("bundles", {})
    if not bundles:
        raise ValueError("manifest has no bundles to generate from")
    files = {}
    members = {b: resolve_bundle(bundles, b) for b in bundles}

    if layout == "per-bundle":
        entries = []
        for b, spec in bundles.items():
            desc = spec.get("description", b)
            base = f"plugins/{b}"
            files[f"{base}/.claude-plugin/plugin.json"] = _plugin_json(b, desc, author)
            files[f"{base}/commands/install.md"] = _install_command(b, desc, members[b])
            entries.append({
                "name": b,
                "description": desc,
                "source": f"./plugins/{b}",
                "category": "bundle",
            })
    elif layout == "single":
        base = "plugins/kitbag"
        files[f"{base}/.claude-plugin/plugin.json"] = _plugin_json(
            "kitbag", "Install curated kitbag bundles via slash commands", author)
        for b, spec in bundles.items():
            files[f"{base}/commands/{b}.md"] = _install_command(
                b, spec.get("description", b), members[b])
        entries = [{
            "name": "kitbag",
            "description": "Curated bundle installers (one command per bundle)",
            "source": "./plugins/kitbag",
            "category": "bundle",
        }]
    else:
        raise ValueError(f"unknown layout '{layout}' (use per-bundle or single)")

    files[".claude-plugin/marketplace.json"] = _marketplace_json(
        name, description, author, entries)
    files["README.md"] = _readme(name, bundles, layout)
    return files


def write_tree(out_dir, files):
    """Write {relpath: contents} under out_dir. Returns sorted list of paths."""
    out = Path(out_dir)
    written = []
    for rel, content in files.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
        written.append(str(p))
    return sorted(written)
